#!/usr/bin/env python3
"""Build the weapons of the System Reference Document 5.2.1.

The SRD 5.2.1 is published by Wizards of the Coast under CC-BY-4.0 (see
SRD_ATTRIBUTION.md). This reads the Weapons table of its "Equipment" chapter
(page 91) and writes it into the data block of `utils/srdWeapons.ts`, a file
kept identical in the backend and the frontend:

    python3 scripts/srd-weapons.py SRD_CC_v5.2.1.pdf

Needs `pdftotext` (poppler). The PDF is at https://www.dndbeyond.com/srd and
is not kept in this repository.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGETS = [ROOT / "backend/src/utils/srdWeapons.ts", ROOT / "frontend/src/utils/srdWeapons.ts"]
BEGIN = "// --- weapons: generated by scripts/srd-weapons.py ---"
END = "// --- end of weapons ---"
MASTERIES = {"Cleave", "Graze", "Nick", "Push", "Sap", "Slow", "Topple", "Vex"}
ROW = re.compile(
    r"^\s{4,8}(?P<name>[A-Z][A-Za-z' ]+?)\s+(?P<damage>\d+(?:d\d+)?) (?P<type>[A-Z][a-z]+)\s+(?P<props>.*?)\s+"
    r"(?P<mastery>" + "|".join(sorted(MASTERIES)) + r")\s+(?P<weight>[\d/]+ lb\.|—)\s+(?P<cost>\d+ [CSGP]P)\s*$"
)
CATEGORIES = {
    "Simple Melee Weapons": ("simple", "melee"),
    "Simple Ranged Weapons": ("simple", "ranged"),
    "Martial Melee Weapons": ("martial", "melee"),
    "Martial Ranged Weapons": ("martial", "ranged"),
}


def properties(text):
    """The Properties cell as a list, with a range or a damage kept in its property."""
    if text.strip() in ("", "—"):
        return []
    return [part.strip() for part in re.split(r",\s*(?![^()]*\))", text) if part.strip()]


def weapons(pdf):
    text = subprocess.run(["pdftotext", "-layout", "-f", "91", "-l", "91", pdf, "-"], check=True, capture_output=True, text=True).stdout
    found, category = [], None
    for line in text.splitlines():
        heading = line.strip()
        if heading in CATEGORIES:
            category = CATEGORIES[heading]
            continue
        match = ROW.match(line)
        if match and category:
            found.append({**match.groupdict(), "category": category, "props": properties(match["props"])})
        elif found and category and line.startswith(" " * 30) and line.strip():
            # The Properties cell carried on to a second line.
            found[-1]["props"] += properties(line.strip())
    out = []
    for row in found:
        props = row["props"]
        reach = any(p == "Reach" for p in props)
        span = next((re.search(r"Range (\d+)/(\d+)", p) for p in props if "Range" in p), None)
        versatile = next((re.search(r"Versatile \((\d+d\d+)\)", p) for p in props if p.startswith("Versatile")), None)
        out.append(
            {
                "name": row["name"].strip(),
                "category": row["category"][0],
                "kind": row["category"][1],
                "damage": row["damage"],
                "damageType": row["type"].lower(),
                "properties": props,
                "mastery": row["mastery"],
                **({"range": {"normal": int(span[1]), "long": int(span[2])}} if span else {}),
                **({"versatile": versatile[1]} if versatile else {}),
                **({"reach": True} if reach else {}),
                "weight": row["weight"],
                "cost": row["cost"],
            }
        )
    return out


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    found = weapons(sys.argv[1])
    if len(found) != 38:
        raise SystemExit(f"Found {len(found)} weapons, not the table's 38: the page has changed")
    block = BEGIN + "\nexport const SRD_WEAPONS: readonly SrdWeapon[] = " + json.dumps(found, indent=2, ensure_ascii=False) + ";\n" + END
    for target in TARGETS:
        source = target.read_text(encoding="utf-8")
        start, end = source.index(BEGIN), source.index(END) + len(END)
        target.write_text(source[:start] + block + source[end:], encoding="utf-8")
    print(f"Wrote {len(found)} weapons to {', '.join(str(t.relative_to(ROOT)) for t in TARGETS)}")


if __name__ == "__main__":
    main()
