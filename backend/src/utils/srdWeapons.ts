const BY_NAME = new Map(SRD_WEAPONS.map((weapon) => [weapon.name.toLowerCase(), weapon]));

/** The SRD weapon of this name, ignoring case and spacing, or null. */
export function findSrdWeapon(name: string | null | undefined): SrdWeapon | null {
  return name ? (BY_NAME.get(name.trim().toLowerCase().replace(/\s+/g, ' ')) ?? null) : null;
}

export function hasWeaponProperty(weapon: SrdWeapon, property: string): boolean {
  return weapon.properties.some((entry) => entry.toLowerCase().startsWith(property.toLowerCase()));
}

/**
 * Whether a sheet's weapon proficiencies, as written ("Simple and Martial
 * weapons", "Simple weapons and Martial weapons that have the Finesse or
 * Light property", "Daggers, Longswords"), cover a weapon.
 */
export function proficientWith(weapon: SrdWeapon, written: string | null | undefined): boolean {
  const text = (written ?? '').toLowerCase();
  if (!text.trim()) return false;
  const name = weapon.name.toLowerCase();
  if (text.includes(name) || text.includes(`${name}s`) || text.includes(name.replace(/s$/, ''))) return true;
  if (weapon.category === 'simple') return /\bsimple\b/.test(text);
  if (!/\bmartial\b/.test(text)) return false;
  // "Martial weapons that have the Finesse or Light property": only those.
  const only = /martial weapons? (?:that|with) (?:have |has )?(?:the )?([a-z-]+)(?: or (?:the )?([a-z-]+))? propert/.exec(text);
  if (!only) return true;
  return [only[1], only[2]].some((property) => property && hasWeaponProperty(weapon, property));
}

export interface Wielder {
  /** Ability modifiers. */
  str: number;
  dex: number;
  proficiencyBonus: number;
  /** Proficient with the weapon: Proficiency Bonus is added to the attack roll. */
  proficient: boolean;
}

/** A sheet's attack, as the D&D 5e sheet keeps one. */
export interface WeaponAttack {
  name: string;
  attackBonus: number;
  damageRoll: string;
  damageType: string;
  /** Feet: the normal range of a ranged or thrown weapon, the reach of a melee one. */
  range: number;
  properties: string[];
  notes: string;
}

/**
 * The attack a weapon makes for a character, by the rules: Strength for a
 * melee weapon, Dexterity for a ranged one, the better of the two with
 * Finesse; the Proficiency Bonus on the attack roll when proficient; the
 * modifier on the damage. The mastery and a Versatile weapon's two-handed
 * damage are put in the notes.
 */
export function weaponAttack(weapon: SrdWeapon, wielder: Wielder): WeaponAttack {
  const finesse = hasWeaponProperty(weapon, 'finesse');
  const modifier = finesse ? Math.max(wielder.str, wielder.dex) : weapon.kind === 'ranged' ? wielder.dex : wielder.str;
  const sign = modifier < 0 ? '-' : '+';
  const damageRoll = modifier === 0 ? weapon.damage : `${weapon.damage}${sign}${Math.abs(modifier)}`;
  const notes = [
    weapon.versatile ? `Two hands: ${weapon.versatile}${modifier === 0 ? '' : `${sign}${Math.abs(modifier)}`}` : null,
    `Mastery: ${weapon.mastery}`,
  ].filter((note): note is string => note !== null);
  return {
    name: weapon.name,
    attackBonus: modifier + (wielder.proficient ? wielder.proficiencyBonus : 0),
    damageRoll,
    damageType: weapon.damageType,
    range: weapon.kind === 'ranged' ? (weapon.range?.normal ?? 5) : weapon.reach ? 10 : 5,
    properties: [...weapon.properties],
    notes: notes.join('. '),
  };
}
