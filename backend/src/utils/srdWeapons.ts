export type WeaponMastery = 'Cleave' | 'Graze' | 'Nick' | 'Push' | 'Sap' | 'Slow' | 'Topple' | 'Vex';

export interface SrdWeapon {
  name: string;
  category: 'simple' | 'martial';
  kind: 'melee' | 'ranged';
  /** "1d8", or "1" for the Blowgun. */
  damage: string;
  damageType: string;
  /** As the table prints them: "Finesse", "Thrown (Range 20/60)", "Versatile (1d10)". */
  properties: string[];
  mastery: WeaponMastery;
  /** A thrown or ammunition weapon's normal and long range, in feet. */
  range?: { normal: number; long: number };
  /** The damage die with two hands, for a Versatile weapon. */
  versatile?: string;
  /** It adds 5 feet to its wielder's reach. */
  reach?: true;
  weight: string;
  cost: string;
}

